/**
 * 全局配置 —— 小程序端所有「环境相关」的取值都集中在这里，改一处即可切换部署形态。
 *
 * 注意：不使用可选链（?.）与空值合并（??），以兼容较低基础库版本。
 */

/* ============================================================
 * 1. 传输方式（最重要的开关）
 * ============================================================
 *
 * 'direct'          —— wx.request 直连后端。本地开发默认用这个。
 *                      限制：开发者工具需勾选「不校验合法域名」；
 *                      真机体验版/正式版必须是 https 且已在后台登记 request 合法域名。
 *
 * 'cloud-function'  —— 经云函数 proxyTrip 中转，绕开合法域名限制。
 *                      前提：后端必须公网可访问，且云函数超时已调到 60s。
 *                      详见 cloudfunctions/proxyTrip/index.js 顶部说明。
 *
 * 'cloud-container' —— 经微信云托管 callContainer 调用，后端容器跑在微信云托管里。
 *                      真机 / 体验版要跑通，这是最省事的一条路：
 *                        · callContainer 走微信内网，**不需要在小程序后台配 request 合法域名**，
 *                          也就**不需要备案域名**（这正是 `direct` 在真机上走不通的原因）；
 *                        · 可以在云托管控制台**关掉公网访问**，只有本小程序能调，
 *                          天然防白嫖，不必额外依赖 AUTH_MODE。
 *                      需要额外填 CLOUD_CONTAINER_ENV 与 CLOUD_CONTAINER_SERVICE（见下）。
 *                      部署步骤见 backend/DEPLOY-CLOUDRUN.md。
 */
var TRANSPORT = 'direct'

/* ============================================================
 * 2. 直连模式（direct）
 * ============================================================ */

// 后端服务地址（结尾不要带 /）
var BASE_URL = 'http://localhost:8000'

// 接口超时时间（毫秒）
// 多智能体规划「并行检索 + 行程生成」实测 17~25s，默认 60s 余量偏小，
// 这里放宽到 115s（wx.request 允许的上限附近）。
var REQUEST_TIMEOUT = 115000

/* ============================================================
 * 3. 云函数中转模式（cloud-function）
 * ============================================================ */

// 云函数目录名，必须与 cloudfunctions/ 下的文件夹名完全一致（大小写敏感）
var CLOUD_PROXY_NAME = 'proxyTrip'

/* ============================================================
 * 4. 云托管模式（cloud-container）
 * ============================================================ */

// 云托管服务名，对应 callContainer 请求头 X-WX-SERVICE 的值。
// 必须与「微信云托管控制台 → 服务管理 → 服务列表」里的服务名称完全一致。
var CLOUD_CONTAINER_SERVICE = 'trip-api'

/* ⚠️ 下面两个环境 ID 不是同一个东西，别混用。
 *
 * 微信官方 FAQ 写得很明确：「微信云托管和微信云开发是两套独立体系，
 * 微信云托管的环境只能在微信云托管控制台看到，在微信开发者工具的
 * 云开发控制台中不能看到。」
 *
 *   CLOUD_ENV           = 微信云开发环境 ID（形如 cloud1-xxxxxxxx）
 *                         → 给 wx.cloud.init / wx.cloud.database() 用，即云数据库。
 *
 *   CLOUD_CONTAINER_ENV = 微信云托管环境 ID（形如 trip-planner-xxxxxxxx）
 *                         → 给 wx.cloud.callContainer 的 config.env 用。
 *                         ⚠️ 该参数必填且不能为空。
 *                         ⚠️ 新建环境时填的是「环境名称」，平台会在其后追加一串字符
 *                            组成完整的环境 ID —— 复制时别只抄名称。
 *                            名称只能用数字 / 小写字母 / -，最多 20 字符（填不了中文）。
 *
 * 之所以拆成两个常量：本项目同时用了云数据库（云开发）与云托管（后端容器），
 * 它们各自的环境 ID 来自不同控制台。早期版本用一个常量喂两处，属于双份真相，
 * 一旦两个环境不同就会报 -601002 / 环境不存在。
 *
 * 留空则回退使用 CLOUD_ENV —— 仅当你确认两者恰好在同一个环境时才这样用。
 */
var CLOUD_ENV = 'cloud1-d5gan8twf7e51b2cf'
var CLOUD_CONTAINER_ENV = ''

/* ============================================================
 * 5. 云数据库（行程跨设备可见）
 * ============================================================
 *
 * 开启后：行程会额外存一份到云数据库集合 `trips`，
 * 换设备 / 重装后仍能看到自己生成过的行程。
 *
 * 前置条件（只做一次）：
 *   云开发控制台 → 数据库 → 新建集合「trips」→ 权限选「仅创建者可读写」。
 *   集合不存在时**不会报错阻断**，只是自动退化为纯本地缓存
 *   （Console 里会给一条提示，见 utils/cloudStore.js）。
 *
 * 关掉这个开关即可完全回到「纯本地」行为。
 */
var USE_CLOUD_DB = true

/* ============================================================
 * 6. AI 生成内容标识（合规相关，勿随手删除）
 * ============================================================
 *
 * 依据《人工智能生成合成内容标识办法》（2025-09-01 起施行），生成合成内容
 * 需要添加「显式标识」——以文字形式向用户提示内容由 AI 生成，并且要求
 * **显著、持续可见**：不能塞在角落小字里，也不能只提示一次就消失。
 *
 * 本项目的落地方式（三处 + 一处导出）：
 *   1. 首页提交前告知一次，避免用户对结果来源产生误解；
 *   2. 结果页顶部常驻标识条（进页面即可见）；
 *   3. 结果页底部完整免责声明（滚动到底仍在）；
 *   4. 「复制行程」导出的纯文本同样带标识 —— 内容一旦离开小程序，标识要跟着走。
 *
 * 这里是标识文案的**唯一来源**，改文案只改这一处。
 */
var AI_LABEL = {
  badge: 'AI 生成',
  notice: '以下行程由 AI 自动生成，仅供参考',
  disclaimer:
    '本行程由 AI 自动生成，仅供参考，不构成出行建议；' +
    '景点开放时间、票价、交通与天气请以官方最新信息为准。',
  producer: '智能旅行助手'
}

module.exports = {
  TRANSPORT: TRANSPORT,

  BASE_URL: BASE_URL,
  REQUEST_TIMEOUT: REQUEST_TIMEOUT,

  CLOUD_PROXY_NAME: CLOUD_PROXY_NAME,

  CLOUD_CONTAINER_SERVICE: CLOUD_CONTAINER_SERVICE,
  CLOUD_CONTAINER_ENV: CLOUD_CONTAINER_ENV,
  CLOUD_ENV: CLOUD_ENV,

  USE_CLOUD_DB: USE_CLOUD_DB,

  AI_LABEL: AI_LABEL
}
